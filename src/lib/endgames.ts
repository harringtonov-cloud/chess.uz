/**
 * Грубая проверка записи FEN без шахматного движка: пусто — значит выглядит корректно.
 * Проверяет 6 полей, 8 горизонталей по 8 клеток, по одному королю, право хода.
 */
export function fenProblems(fen: string): string[] {
  const out: string[] = [];
  const parts = fen.trim().split(/\s+/);
  if (parts.length !== 6) out.push('нужно 6 полей FEN');
  const ranks = (parts[0] ?? '').split('/');
  if (ranks.length !== 8) out.push('нужно 8 горизонталей');
  ranks.forEach((r, i) => {
    let n = 0;
    for (const ch of r) n += /[1-8]/.test(ch) ? Number(ch) : /[pnbrqkPNBRQK]/.test(ch) ? 1 : 100;
    if (n !== 8) out.push(`горизонталь ${8 - i}: ${n} клеток вместо 8`);
  });
  const board = parts[0] ?? '';
  if ((board.match(/K/g) ?? []).length !== 1) out.push('должен быть один белый король');
  if ((board.match(/k/g) ?? []).length !== 1) out.push('должен быть один чёрный король');
  if (parts[1] !== 'w' && parts[1] !== 'b') out.push('право хода должно быть w или b');
  if (/[Pp]/.test(ranks[0] ?? '') || /[Pp]/.test(ranks[7] ?? '')) out.push('пешки на крайних горизонталях');
  return out;
}
